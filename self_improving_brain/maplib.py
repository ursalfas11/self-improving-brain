"""INDEX.md: the map an agent reads first. Generated from frontmatter, never edited by hand.

Kept short on purpose — one line per note, no numbers, so it stays cheap to load every session.
"""
from __future__ import annotations

from collections import defaultdict

from .config import Vault
from .notes import Library
from .util import short

HEADER = ("> Map, not storage. Generated by `brain index` from each note's frontmatter — do not edit.\n"
          "> Search with `brain search \"<question>\"`, open with `brain read <note> [section]`.\n")


def render(lib: Library) -> str:
    groups: dict[str, list] = defaultdict(list)
    for n in lib.notes.values():
        folder = n.rel.split("/")[0] if "/" in n.rel else "(root)"
        groups[folder].append(n)
    out = ["# Brain index", "", HEADER]
    for folder in sorted(groups):
        notes = sorted(groups[folder], key=lambda n: (not n.is_hub, n.name))
        out.append(f"## `{folder}/`")
        for n in notes:
            hook = f" — {short(n.description, 100)}" if n.description else ""
            out.append(f"- [[{n.name}]]{hook}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def write(v: Vault) -> bool:
    text = render(Library(v.root))
    p = v.root / "INDEX.md"
    old = p.read_text(encoding="utf-8") if p.exists() else ""
    if old == text:
        return False
    p.write_text(text, encoding="utf-8")
    return True
